  colProblemId: "Problem ID",
  colRegion: "Region",
  colSolvedCount: "Teams solved",
  colAvgScore: "Avg score",
  colDeployments: "Deploys (ok / total)",
  colOccurredAt: "Occurred at",
  colSource: "Source",
  colPoints: "Points",
