/**
 * [Composite Runtime / Issue #2061] Repository for composite parent + per-target
 * deployment rows.
 *
 * Storage / persistence only — this module does NOT start deployments, publish
 * EventBridge events, invoke adapters, aggregate state, or touch the HTTP API.
 * It persists a parent coordination row and N independent target rows, and reads
 * them back (a parent, a single target, or a parent's targets in ordinal order).
 *
 * Dependencies are injected (`ddb` + `tableName`); the repository never
 * constructs a DynamoDB client itself.
 *
 * Idempotency / conflict semantics (issue #2061):
 *   - Re-writing a target with the same `targetDeploymentId` and identical
 *     immutable fields is a no-op success.
 *   - Re-writing the same `targetDeploymentId` with different immutable fields
 *     (parent / targetId / ordinal / provider / engine / entry) fails loudly.
 *   - Two different `targetDeploymentId`s sharing a `targetId` under the same
 *     parent fail loudly; the same `targetId` under a different parent is fine.
 *   - Creating the parent and each target is not one transaction. Partial state
 *     (parent + targets 0..N-1) is left observable; no status mutation, no
 *     cleanup.
 */

import { type DynamoDBDocumentClient, PutCommand } from "@aws-sdk/lib-dynamodb";
import {
  COMPOSITE_RUNTIME_KIND,
  COMPOSITE_VERSION,
  type CompositeParentDeploymentItem,
  type CompositeTargetDeploymentItem,
  compositeTargetGsi3Pk,
  compositeTargetGsi3Sk,
  deploymentPk,
  MAX_COMPOSITE_TARGETS,
  MIN_COMPOSITE_TARGETS,
} from "./composite-deployment.js";
import { resolveDeploymentsRepository } from "./shared.js";
import type { DeploymentStatus } from "./types.js";

const CONDITION_PK_ABSENT = "attribute_not_exists(PK)";

export type CompositeParentDeploymentRecord = Omit<CompositeParentDeploymentItem, "PK" | "SK">;
export type CompositeTargetDeploymentRecord = Omit<
  CompositeTargetDeploymentItem,
  "PK" | "SK" | "GSI3PK" | "GSI3SK"
>;

/** Injected dependencies. The `ddb` client is created by the caller, not here. */
export interface CompositeDeploymentRepositoryDeps {
  readonly ddb: Pick<DynamoDBDocumentClient, "send">;
  readonly tableName: string;
}

/** Raised when a target write conflicts with an already-persisted row. */
export class CompositeTargetConflictError extends Error {
  constructor(
    public readonly targetDeploymentId: string,
    public readonly reason: string,
  ) {
    super(`composite target ${targetDeploymentId} conflict: ${reason}`);
    this.name = "CompositeTargetConflictError";
  }
}

/** Raised when a parent write conflicts with an already-persisted parent row. */
export class CompositeParentConflictError extends Error {
  constructor(
    public readonly parentDeploymentId: string,
    public readonly reason: string,
  ) {
    super(`composite parent ${parentDeploymentId} conflict: ${reason}`);
    this.name = "CompositeParentConflictError";
  }
}

export interface CreateCompositeParentInput {
  readonly parentDeploymentId: string;
  readonly tenantId: string;
  readonly problemId: string;
  /** 2..8 — mirrors the composite metadata target count. */
  readonly targetCount: number;
  readonly createdAt: string;
  readonly updatedAt?: string;
  readonly expiresAt: number;
  readonly status?: DeploymentStatus;
  /** [#2063] Team identity shared across the parent + every target row. */
  readonly teamName?: string;
  readonly teamLoginKey?: string;
  /** Existing deploy-request grouping fields, shared across parent + targets. */
  readonly accountGroupId?: string;
  readonly problemSetId?: string;
}

export interface CreateCompositeTargetInput {
  /** Globally unique id generated by the caller; becomes the row's `DEPLOYMENT#{id}`. */
  readonly targetDeploymentId: string;
  readonly parentDeploymentId: string;
  readonly targetId: string;
  readonly targetOrdinal: number;
  readonly tenantId: string;
  readonly problemId: string;
  readonly provider: string;
  readonly engine: string;
  readonly entry: string;
  readonly awsAccountId: string;
  readonly region: string;
  readonly teamName: string;
  readonly namePrefix: string;
  readonly teamLoginKey: string;
  readonly createdAt: string;
  readonly updatedAt?: string;
  readonly expiresAt: number;
  readonly status?: DeploymentStatus;
  readonly competitorRoleArn?: string;
  readonly externalIdParameterName?: string;
  readonly displayTeamName?: string;
  readonly accountGroupId?: string;
  readonly problemSetId?: string;
}

function isConditionalCheckFailed(err: unknown): boolean {
  return (err as { name?: string } | undefined)?.name === "ConditionalCheckFailedException";
}

/**
 * Create the composite parent coordination row. Idempotent: re-creating with the
 * same immutable identity (tenant / problem / targetCount / shared team and
 * grouping fields) returns the existing row; a divergent re-create fails with
 * {@link CompositeParentConflictError}.
 */
export async function createCompositeParent(
  deps: CompositeDeploymentRepositoryDeps,
  input: CreateCompositeParentInput,
): Promise<CompositeParentDeploymentItem> {
  if (
    !Number.isInteger(input.targetCount) ||
    input.targetCount < MIN_COMPOSITE_TARGETS ||
    input.targetCount > MAX_COMPOSITE_TARGETS
  ) {
    throw new RangeError(
      `composite targetCount must be an integer in [${MIN_COMPOSITE_TARGETS}, ${MAX_COMPOSITE_TARGETS}], got ${input.targetCount}`,
    );
  }

  const item: CompositeParentDeploymentItem = {
    PK: deploymentPk(input.parentDeploymentId),
    SK: "META",
    jobId: input.parentDeploymentId,
    tenantId: input.tenantId,
    problemId: input.problemId,
    runtimeKind: COMPOSITE_RUNTIME_KIND,
    compositeVersion: COMPOSITE_VERSION,
    targetCount: input.targetCount,
    status: input.status ?? "PENDING",
    createdAt: input.createdAt,
    updatedAt: input.updatedAt ?? input.createdAt,
    expiresAt: input.expiresAt,
    ...(input.teamName ? { teamName: input.teamName } : {}),
    ...(input.teamLoginKey ? { teamLoginKey: input.teamLoginKey } : {}),
    ...(input.accountGroupId ? { accountGroupId: input.accountGroupId } : {}),
    ...(input.problemSetId ? { problemSetId: input.problemSetId } : {}),
  };

  try {
    await deps.ddb.send(
      new PutCommand({
        TableName: deps.tableName,
        Item: item,
        ConditionExpression: CONDITION_PK_ABSENT,
      }),
    );
    return item;
  } catch (err) {
    if (!isConditionalCheckFailed(err)) throw err;
    const existing = await getCompositeParent(deps, input.parentDeploymentId);
    if (
      existing &&
      existing.tenantId === item.tenantId &&
      existing.problemId === item.problemId &&
      existing.targetCount === item.targetCount &&
      existing.teamName === item.teamName &&
      existing.teamLoginKey === item.teamLoginKey &&
      existing.accountGroupId === item.accountGroupId &&
      existing.problemSetId === item.problemSetId
    ) {
      return item;
    }
    throw new CompositeParentConflictError(
      input.parentDeploymentId,
      "a different parent row already exists at this id",
    );
  }
}

/**
 * Create one composite target row. See module docs for idempotency / conflict
 * rules. Creates the parent's targets one at a time (the caller drives ordinal
 * order); a per-write target-id uniqueness check scopes to the parent.
 */
export async function createCompositeTarget(
  deps: CompositeDeploymentRepositoryDeps,
  input: CreateCompositeTargetInput,
): Promise<CompositeTargetDeploymentItem> {
  if (!Number.isInteger(input.targetOrdinal) || input.targetOrdinal < 0) {
    throw new RangeError(
      `composite targetOrdinal must be a non-negative integer, got ${input.targetOrdinal}`,
    );
  }

  const item = buildCompositeTargetItem(input);

  // 1. A row already at this targetDeploymentId → idempotent if immutables match,
  //    otherwise a loud conflict (never a silent overwrite).
  const existing = await getRawRow(deps, input.targetDeploymentId);
  if (existing) {
    if (!isCompositeTargetRecord(existing)) {
      throw new CompositeTargetConflictError(
        input.targetDeploymentId,
        "a non-composite-target row already exists at this id",
      );
    }
    if (immutableTargetFieldsMatch(existing, item)) return item;
    throw new CompositeTargetConflictError(
      input.targetDeploymentId,
      "an existing target row has different immutable fields",
    );
  }

  // 2. targetId must be unique within the parent (a different deploymentId reusing
  //    the same targetId under the same parent is a conflict).
  const siblings = await listCompositeTargets(deps, input.parentDeploymentId);
  const clash = siblings.find(
    (sibling) => sibling.targetId === input.targetId && sibling.jobId !== item.jobId,
  );
  if (clash) {
    throw new CompositeTargetConflictError(
      input.targetDeploymentId,
      `targetId ${input.targetId} already used by ${clash.jobId} under parent ${input.parentDeploymentId}`,
    );
  }

  // 3. Persist, guarding against a concurrent writer racing the same PK.
  try {
    await deps.ddb.send(
      new PutCommand({
        TableName: deps.tableName,
        Item: item,
        ConditionExpression: CONDITION_PK_ABSENT,
      }),
    );
  } catch (err) {
    if (isConditionalCheckFailed(err)) {
      throw new CompositeTargetConflictError(
        input.targetDeploymentId,
        "a row was created concurrently at this id",
      );
    }
    throw err;
  }
  return item;
}

/** Read a composite parent row, or undefined if absent / not a parent row. */
export async function getCompositeParent(
  deps: CompositeDeploymentRepositoryDeps,
  parentDeploymentId: string,
): Promise<CompositeParentDeploymentRecord | undefined> {
  const row = await getRawRow(deps, parentDeploymentId);
  return isCompositeParentRecord(row) ? row : undefined;
}

/** Read a composite target row, or undefined if absent / not a target row. */
export async function getCompositeTarget(
  deps: CompositeDeploymentRepositoryDeps,
  targetDeploymentId: string,
): Promise<CompositeTargetDeploymentRecord | undefined> {
  const row = await getRawRow(deps, targetDeploymentId);
  return isCompositeTargetRecord(row) ? row : undefined;
}

/**
 * List a parent's target rows in targetOrdinal order via GSI3. Returns whatever
 * targets currently exist — partial creation is observable, not hidden.
 */
export async function listCompositeTargets(
  deps: CompositeDeploymentRepositoryDeps,
  parentDeploymentId: string,
): Promise<CompositeTargetDeploymentRecord[]> {
  const repository = await resolveDeploymentsRepository(deps);
  const rows = await repository.listCompositeTargets(parentDeploymentId);
  // The sparse GSI3 is populated only by composite target rows. The pre-seam
  // `isCompositeTargetItem` guard depended on SK === "META", but the repository
  // returns domain records with physical keys stripped, so that check is both
  // impossible and redundant here.
  return rows.filter(isCompositeTargetRecord);
}

async function getRawRow(
  deps: CompositeDeploymentRepositoryDeps,
  deploymentId: string,
): Promise<Record<string, unknown> | undefined> {
  const repository = await resolveDeploymentsRepository(deps);
  return (await repository.getDeployment(deploymentId)) as Record<string, unknown> | undefined;
}

function isCompositeParentRecord(row: unknown): row is CompositeParentDeploymentRecord {
  return (row as { runtimeKind?: unknown } | undefined)?.runtimeKind === COMPOSITE_RUNTIME_KIND;
}

function isCompositeTargetRecord(row: unknown): row is CompositeTargetDeploymentRecord {
  return (
    typeof (row as { parentDeploymentId?: unknown } | undefined)?.parentDeploymentId === "string"
  );
}

function buildCompositeTargetItem(
  input: CreateCompositeTargetInput,
): CompositeTargetDeploymentItem {
  return {
    PK: deploymentPk(input.targetDeploymentId),
    SK: "META",
    jobId: input.targetDeploymentId,
    problemId: input.problemId,
    tenantId: input.tenantId,
    awsAccountId: input.awsAccountId,
    region: input.region,
    teamName: input.teamName,
    namePrefix: input.namePrefix,
    teamLoginKey: input.teamLoginKey,
    status: input.status ?? "PENDING",
    createdAt: input.createdAt,
    updatedAt: input.updatedAt ?? input.createdAt,
    expiresAt: input.expiresAt,
    parentDeploymentId: input.parentDeploymentId,
    targetId: input.targetId,
    targetOrdinal: input.targetOrdinal,
    runtimeProvider: input.provider,
    runtimeEngine: input.engine,
    runtimeEntry: input.entry,
    GSI3PK: compositeTargetGsi3Pk(input.parentDeploymentId),
    GSI3SK: compositeTargetGsi3Sk(input.targetOrdinal, input.targetId),
    ...(input.competitorRoleArn ? { competitorRoleArn: input.competitorRoleArn } : {}),
    ...(input.externalIdParameterName
      ? { externalIdParameterName: input.externalIdParameterName }
      : {}),
    ...(input.displayTeamName ? { displayTeamName: input.displayTeamName } : {}),
    ...(input.accountGroupId ? { accountGroupId: input.accountGroupId } : {}),
    ...(input.problemSetId ? { problemSetId: input.problemSetId } : {}),
  };
}

function immutableTargetFieldsMatch(
  existing: CompositeTargetDeploymentRecord,
  next: CompositeTargetDeploymentItem,
): boolean {
  return (
    existing.parentDeploymentId === next.parentDeploymentId &&
    existing.targetId === next.targetId &&
    existing.targetOrdinal === next.targetOrdinal &&
    existing.runtimeProvider === next.runtimeProvider &&
    existing.runtimeEngine === next.runtimeEngine &&
    existing.runtimeEntry === next.runtimeEntry
  );
}
